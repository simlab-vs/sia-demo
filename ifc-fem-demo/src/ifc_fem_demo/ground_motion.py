"""Ground-motion model: Akkar, Sandikkaya & Bommer (2014), hypocentral-distance form.

Given a magnitude, a hypocentral distance, a faulting mechanism and the site's
Vs30, the model predicts the 5%-damped pseudo-spectral acceleration at periods
from 0.01 s to 4 s plus PGA, as a median and a log-normal scatter:

    ln SA = ln SA_rock(M, R_hyp, mechanism) + ln S(Vs30, PGA_rock) +/- sigma

The rock term is the regression of eq. (2) in the paper, the site term the
non-linear amplification of eq. (3), and sigma the total standard deviation
(between-event tau and within-event phi combined). Units are g.

Reference: Akkar S., Sandikkaya M.A., Bommer J.J. (2014), "Empirical
ground-motion models for point- and extended-source crustal earthquake
scenarios in Europe and the Middle East", Bull. Earthquake Eng. 12:359-387.
Coefficients as transcribed in OpenQuake hazardlib (gsim/akkar_2014.py,
class AkkarEtAlRhyp2014), whose verification tables come from the authors'
own code. Valid for Mw 4-8 and hypocentral distances up to 200 km.
"""

