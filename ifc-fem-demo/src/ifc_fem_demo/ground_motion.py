PERIODS = COEFFICIENTS["period"][1:]


@dataclass(frozen=True)
class Prediction:
    """Median and log-normal scatter of the response spectrum, in g. Period 0 is PGA."""

    periods: np.ndarray
    median: np.ndarray  # g
    sigma: np.ndarray  # total standard deviation of ln(SA)

    @property
    def median_plus_sigma(self) -> np.ndarray:
        return self.median * np.exp(self.sigma)


def mechanism_flags(rake_deg: float) -> tuple[int, int]:
    """(normal, reverse) dummy variables; anything else counts as strike-slip."""
    normal = -135.0 < rake_deg < -45.0
    reverse = 45.0 < rake_deg < 135.0
    return int(normal), int(reverse)


def ln_rock_motion(c: np.ndarray, magnitude: float, rhyp_km: float, rake_deg: float) -> np.ndarray:
    """Eq. (2): ln of the median motion on reference rock (Vs30 = 750 m/s)."""
    normal, reverse = mechanism_flags(rake_deg)
    dm = magnitude - HINGE_MAGNITUDE
    magnitude_slope = c["a2"] if magnitude <= HINGE_MAGNITUDE else c["a7"]
    return (
        c["a1"]
        + magnitude_slope * dm
        + c["a3"] * (8.5 - magnitude) ** 2
        + (c["a4"] + c["a5"] * dm) * np.log(np.sqrt(rhyp_km**2 + c["a6"] ** 2))
        + c["a8"] * normal
        + c["a9"] * reverse
    )


def ln_site_amplification(c: np.ndarray, vs30: float, pga_rock_g: float) -> np.ndarray:
    """Eq. (3): soil amplification, non-linear in the rock PGA for Vs30 below 750 m/s."""
    ratio = min(vs30, VS30_CAP) / REFERENCE_VS30
    linear = c["b1"] * np.log(ratio)
    if vs30 >= REFERENCE_VS30:
        return linear
    stiffness = NONLINEAR_C * ratio**NONLINEAR_N
    return linear + c["b2"] * np.log((pga_rock_g + stiffness) / ((pga_rock_g + NONLINEAR_C) * ratio**NONLINEAR_N))


def predict(magnitude: float, rhyp_km: float, rake_deg: float, vs30: float) -> Prediction:
    """5%-damped response spectrum (PGA first) for one earthquake at one site."""
    if not 4.0 <= magnitude <= 8.0:
        raise ValueError(f"magnitude {magnitude} is outside the model's Mw 4-8 range")
    if rhyp_km > 200.0:
        raise ValueError(f"hypocentral distance {rhyp_km} km is beyond the model's 200 km range")
    ln_rock = ln_rock_motion(COEFFICIENTS, magnitude, rhyp_km, rake_deg)
    pga_rock_g = float(np.exp(ln_rock[0]))
    ln_median = ln_rock + ln_site_amplification(COEFFICIENTS, vs30, pga_rock_g)
    sigma = np.sqrt(COEFFICIENTS["phi"] ** 2 + COEFFICIENTS["tau"] ** 2)
    return Prediction(COEFFICIENTS["period"].copy(), np.exp(ln_median), sigma)
